/** Data ISO (YYYY-MM-DD) deslocada em `days` a partir de hoje. */
function iso(days: number): string {
  const date = new Date();
  date.setHours(12, 0, 0, 0);
  date.setDate(date.getDate() + days);
  return date.toISOString().slice(0, 10);
}

