import type { AlternativeId, Question } from '@/types';

type QuestionSeed = Omit<Question, 'alternatives'> & {
  alternatives: [string, string, string, string, string];
};

const ALTERNATIVE_IDS: AlternativeId[] = ['A', 'B', 'C', 'D', 'E'];

function createQuestion(seed: QuestionSeed): Question {
  return {
    ...seed,
    alternatives: seed.alternatives.map((text, index) => ({
      id: ALTERNATIVE_IDS[index],
      text,
    })),
  };
}

